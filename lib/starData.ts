/**
 * The sky, as it actually is: every star a naked eye can see, where it is.
 *
 * This is the Yale Bright Star Catalogue cut at magnitude 6.5 - 8404 stars,
 * which is the naked-eye limit under a dark sky and therefore the whole of what
 * anybody has ever drawn from a field at night. Right ascension, declination,
 * visual magnitude and spectral class, at epoch J2000.
 *
 * WHY A REAL CATALOGUE AND NOT NOISE.
 *
 * A procedural star field is cheaper, and for a background it would do. It will
 * not do here, because of what a star sky is FOR in a tool about perspective:
 * it is the one thing in the world with no perspective in it at all. Everything
 * else the tool draws has a vanishing point, gets smaller with distance and
 * converges. The stars are infinitely far away, so they do none of that. Turn
 * around and they do not shift; walk a mile and they do not move; the whole
 * sphere turns rigidly overhead and no figure in it ever changes shape.
 *
 * That lesson is only worth anything if the sky is checkable. Orion has to be
 * Orion - the belt three in a row, Betelgeuse orange at the shoulder, Rigel
 * blue at the knee - because a shape you recognise is a shape you can watch
 * stay the same, and a random dot field is a claim nobody can test. It also
 * means the tool answers a real question an illustrator has: what was over that
 * hill, at that hour, on that night.
 *
 * HOW IT IS PACKED. Six characters a star, twelve bits apiece for right
 * ascension and declination, nine for the magnitude and three for the spectral
 * class. That is five arc minutes at worst - a sixth of the moon's width, well
 * under a pixel at any field this tool draws at - for fifty kilobytes instead
 * of the megabyte the plain numbers would take. Brightest first, so the read
 * can be cut short and still get the sky that matters.
 *
 * The figures are the constellation lines: not sky, but the joining-up somebody
 * did to it, and drawn as its own faint thing precisely because that is the
 * distinction. From d3-celestial, in the same packing, polylines separated by a
 * full stop - 150 runs across the eighty-eight constellations.
 */

const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';

/** The reverse table, built once. */
const VALUE = (() => {
  const table = new Int8Array(128).fill(-1);
  for (let i = 0; i < B64.length; i++) table[B64.charCodeAt(i)] = i;
  return table;
})();

const RA_STEPS = 4096;
const DEC_STEPS = 4096;

/** Two characters, twelve bits. */
const pair = (text: string, at: number) =>
  (VALUE[text.charCodeAt(at)] << 6) | VALUE[text.charCodeAt(at + 1)];

/**
 * A packed coordinate as a unit vector in equatorial coordinates.
 *
 * x toward the vernal equinox, z toward the north celestial pole - the frame
 * the catalogue is written in, and the frame a single rotation carries into the
 * sky over wherever you are standing. See `equatorialToWorld` in lib/sky.ts.
 */
const direction = (raCode: number, decCode: number, into: Float32Array, at: number) => {
  const ra = (raCode / RA_STEPS) * Math.PI * 2;
  const dec = (decCode / (DEC_STEPS - 1)) * Math.PI - Math.PI / 2;
  const flat = Math.cos(dec);
  into[at] = flat * Math.cos(ra);
  into[at + 1] = flat * Math.sin(ra);
  into[at + 2] = Math.sin(dec);
};

/**
 * What colour a star of each spectral class is.
 *
 * Blue-white at the top of the sequence, orange-red at the bottom, and it is a
 * far larger difference than most drawings admit: Betelgeuse and Rigel are in
 * the same constellation, eight degrees apart, and one is plainly orange and
 * the other plainly blue to an unaided eye. Normalised so the brightest channel
 * is 1 - a star's colour is a hue, never a dimming; how bright it is is the
 * magnitude's business.
 */
const CLASS_TINT: [number, number, number][] = [
  [0.61, 0.69, 1.0], // O
  [0.67, 0.75, 1.0], // B
  [0.79, 0.84, 1.0], // A
  [0.98, 0.97, 1.0], // F
  [1.0, 0.96, 0.85], // G
  [1.0, 0.86, 0.67], // K
  [1.0, 0.72, 0.52], // M
  [1.0, 0.96, 0.92], // anything unclassified
];

export interface StarField {
  /** Unit vectors in equatorial coordinates, three floats each. */
  direction: Float32Array;
  /** Visual magnitude. Lower is brighter; Sirius is -1.46. */
  magnitude: Float32Array;
  /** Spectral colour, three floats each. */
  tint: Float32Array;
  count: number;
}

let cached: StarField | null = null;

/** The catalogue, unpacked once and kept. */
export const starField = (): StarField => {
  if (cached) return cached;
  const text = STAR_TEXT.replace(/\n/g, '');
  const count = Math.floor(text.length / 6);
  const field: StarField = {
    direction: new Float32Array(count * 3),
    magnitude: new Float32Array(count),
    tint: new Float32Array(count * 3),
    count,
  };
  for (let i = 0; i < count; i++) {
    const at = i * 6;
    direction(pair(text, at), pair(text, at + 2), field.direction, i * 3);
    const packed = pair(text, at + 4);
    field.magnitude[i] = (packed >> 3) / 50 - 2;
    const tint = CLASS_TINT[packed & 7];
    field.tint[i * 3] = tint[0];
    field.tint[i * 3 + 1] = tint[1];
    field.tint[i * 3 + 2] = tint[2];
  }
  cached = field;
  return field;
};

let figures: Float32Array | null = null;

/**
 * The constellation figures, as loose segments: six floats a segment, both
 * ends in equatorial coordinates.
 *
 * Segments rather than strips because a strip has to be drawn as its own call
 * and there are a hundred and fifty of them; as segments the whole joined-up
 * sky is one buffer and one line.
 */
export const constellationFigures = (): Float32Array => {
  if (figures) return figures;
  const runs = FIGURE_TEXT.replace(/\n/g, '').split('.');
  let segments = 0;
  for (const run of runs) segments += Math.max(0, Math.floor(run.length / 4) - 1);
  const out = new Float32Array(segments * 6);
  let at = 0;
  for (const run of runs) {
    const points = Math.floor(run.length / 4);
    for (let i = 0; i + 1 < points; i++) {
      direction(pair(run, i * 4), pair(run, i * 4 + 2), out, at);
      direction(pair(run, i * 4 + 4), pair(run, i * 4 + 6), out, at + 3);
      at += 6;
    }
  }
  figures = out;
  return out;
};

